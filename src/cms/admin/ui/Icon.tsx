  settings: Settings,
  // Actions / form
  plus: Plus,
  orders: Package,
  reviews: Star,
  abandoned: MailWarning,
  newsletter: Mail,
  bookings: CalendarCheck,
  calendar: Calendar,
  ruler: Ruler,
  shipping: Truck,
  coupons: Ticket,
  'file-edit': FileEdit,
  'refresh-cw': RefreshCw,
